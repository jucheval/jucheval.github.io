// Helper utilities for KMT animation.

export function normal_random() {
    // Adapted from source - https://stackoverflow.com/a/36481059
    // Posted by Maxwell Collard, modified by community. See post 'Timeline' for change history
    // Retrieved 2026-03-26, License - CC BY-SA 4.0
    // Standard Normal variate using Box-Muller transform.
    const u = 1 - Math.random(); // Converting [0,1) to (0,1]
    const v = Math.random();
    return Math.sqrt(-2.0 * Math.log(u)) * Math.cos(2.0 * Math.PI * v)
}

export function normal_cdf(x) {
    // Abramowitz-Stegun style approximation for Phi(x).
    // Generated by Github Copilot

    const a1 = 0.319381530;
    const a2 = -0.356563782;
    const a3 = 1.781477937;
    const a4 = -1.821255978;
    const a5 = 1.330274429;
    const p = 0.2316419;
    const invSqrt2Pi = 0.3989422804014327;

    const z = Math.abs(x);
    const t = 1 / (1 + p * z);
    const poly = (((((a5 * t + a4) * t + a3) * t + a2) * t + a1) * t);
    const pdf = invSqrt2Pi * Math.exp(-0.5 * z * z);
    const cdfPos = 1 - pdf * poly;
    return x >= 0 ? cdfPos : 1 - cdfPos;
}

export function simulateB({
    tEnd = 1,
    dt = 1 / 1024,
    y0 = 0,
} = {}) {
    const stepsFloat = tEnd / dt;
    const steps = Math.round(stepsFloat);
    // Keep an exact grid so t[i] aligns with i*dt in rendering logic.
    if (Math.abs(stepsFloat - steps) > 1e-12) {
        throw new Error("tEnd must be an integer multiple of dt");
    }

    const sqrtDt = Math.sqrt(dt);

    const t = new Array(steps + 1);
    const y = new Array(steps + 1);
    const increments = new Array(steps);

    t[0] = 0;
    y[0] = y0;

    /* Euler-style Brownian updates: W_{i+1} = W_i + sqrt(dt) * Z_i. */
    for (let i = 1; i <= steps; i += 1) {
        t[i] = i * dt;
        const dW = sqrtDt * normal_random();
        increments[i - 1] = dW;
        y[i] = y[i - 1] + dW;
    }

    return {
        dt,
        tEnd,
        steps,
        t,
        y,
        increments,
    };
}

export function computeXfromB(path) {
    const n = path.increments.length;

    const partialSums = path.y;
    const { K, Vjk } = computeVjk(partialSums);
    const { tildeVqk } = compute_tildeVqk(partialSums);

    // Ujk[j][k] stores U_{j,k}; leaves Ujk[0] are the X_k values.
    const Ujk = new Array(K + 1);

    // Top-level quantile coupling: U_{K,0} = G_K(Phi(2^{-K/2} V_{K,0})).
    const topV = Vjk[K][0];
    const topT = normal_cdf(topV / Math.sqrt(2 ** K));
    Ujk[K] = [computeRademacherGj(K, topT)];

    // Dyadic recursion from level j=K down to j=1.
    // \tilde U_{j,k} = G_q(Phi(2^{-j/2} \tilde V_{j,k}) | U_{j,k})
    // then inverts sum/difference to recover children.
    for (let j = K; j >= 1; j -= 1) {
        const parentRow = Ujk[j];
        const childRow = new Array(parentRow.length * 2);

        for (let k = 0; k < parentRow.length; k += 1) {
            const y = parentRow[k];
            const normalizedContrast = tildeVqk[j][k] / Math.sqrt(2 ** j);
            const Z = normal_cdf(normalizedContrast);
            const tildeU = computeRademacherConditionalGq(j, Z, y);

            // With \tilde U = left - right and y = left + right.
            const left = (y + tildeU) / 2;
            const right = (y - tildeU) / 2;

            childRow[2 * k] = Math.round(left);
            childRow[2 * k + 1] = Math.round(right);
        }

        Ujk[j - 1] = childRow;
    }

    const X = Ujk[0];

    return {
        n,
        K,
        X,
        Ujk,
    };
}

export function computeVj(partialSums) {
    const n = partialSums.length - 1;
    const K = Math.round(Math.log2(n));
    const vj = new Array(K + 1);

    // V_j = T_{2^j}, with T_k provided by partialSums[k].
    for (let j = 0; j <= K; j += 1) {
        vj[j] = partialSums[2 ** j];
    }

    return {
        n,
        K,
        vj,
    };
}

export function computeVjk(partialSums) {
    const n = partialSums.length - 1;
    const K = Math.round(Math.log2(n));
    const Vjk = new Array(K + 1);

    // V_{j,k} = T_{(k+1)2^j} - T_{k2^j}, for k = 0..2^{K-j}-1.
    for (let j = 0; j <= K; j += 1) {
        const blockSize = 2 ** j;
        const blockCount = n / blockSize;
        const row = new Array(blockCount);

        for (let k = 0; k < blockCount; k += 1) {
            const left = k * blockSize;
            const right = (k + 1) * blockSize;
            row[k] = partialSums[right] - partialSums[left];
        }

        Vjk[j] = row;
    }

    return {
        n,
        K,
        Vjk,
    };
}

export function compute_tildeVqk(partialSums) {
    const { n, K, Vjk } = computeVjk(partialSums);
    const tildeVqk = new Array(K + 1);
    tildeVqk[0] = null;

    // \tilde V_{q,k} = V_{q-1,2k} - V_{q-1,2k+1}, for q = 1..K.
    for (let q = 1; q <= K; q += 1) {
        const parentRow = Vjk[q - 1];
        if (parentRow.length % 2 !== 0) {
            throw new Error("Internal error: V_{q-1,*} row length must be even");
        }

        const row = new Array(parentRow.length / 2);
        for (let k = 0; k < row.length; k += 1) {
            row[k] = parentRow[2 * k] - parentRow[2 * k + 1];
        }
        tildeVqk[q] = row;
    }

    return {
        n,
        K,
        tildeVqk,
    };
}

function logGamma(z) {
    if (!Number.isFinite(z) || z <= 0) {
        throw new Error("logGamma expects a finite z > 0");
    }

    const p = [
        676.5203681218851,
        -1259.1392167224028,
        771.32342877765313,
        -176.61502916214059,
        12.507343278686905,
        -0.13857109526572012,
        9.9843695780195716e-6,
        1.5056327351493116e-7,
    ];
    const g = 7;

    if (z < 0.5) {
        return Math.log(Math.PI) - Math.log(Math.sin(Math.PI * z)) - logGamma(1 - z);
    }

    let x = 0.99999999999980993;
    const tZ = z - 1;
    for (let i = 0; i < p.length; i += 1) {
        x += p[i] / (tZ + i + 1);
    }

    const t = tZ + g + 0.5;
    return 0.5 * Math.log(2 * Math.PI) + (tZ + 0.5) * Math.log(t) - t + Math.log(x);
}

function logBinomial(n, k) {
    if (!Number.isInteger(n) || n < 0) {
        throw new Error("n must be a non-negative integer");
    }
    if (!Number.isInteger(k)) {
        throw new Error("k must be an integer");
    }
    if (k < 0 || k > n) {
        return Number.NEGATIVE_INFINITY;
    }
    return logGamma(n + 1) - logGamma(k + 1) - logGamma(n - k + 1);
}

export function buildRademacherGjTable(j) {
    if (!Number.isInteger(j) || j < 0 || j > 16) {
        throw new Error("j must be an integer in [0, 16]");
    }

    const m = 2 ** j;
    const values = [];
    const logMass = [];
    const logDen = m * Math.log(2);

    // U_j = sum of m Rademacher variables, support {-m, -m+2, ..., m}.
    for (let u = -m; u <= m; u += 2) {
        const k = (m + u) / 2;
        values.push(u);
        logMass.push(logBinomial(m, k) - logDen);
    }

    const maxLog = Math.max(...logMass);
    const unnormalized = logMass.map((x) => Math.exp(x - maxLog));
    const z = unnormalized.reduce((a, b) => a + b, 0);
    const pmf = unnormalized.map((x) => x / z);

    const cdf = [];
    let acc = 0;
    for (let i = 0; i < pmf.length; i += 1) {
        acc += pmf[i];
        cdf.push(acc);
    }
    cdf[cdf.length - 1] = 1;

    return {
        j,
        m,
        values,
        pmf,
        cdf,
    };
}

function inverseDiscreteCdf(values, cdf, t) {
    if (!Number.isFinite(t)) {
        throw new Error("t must be finite");
    }
    if (t <= 0) {
        return values[0];
    }
    if (t >= 1) {
        return values[values.length - 1];
    }

    let lo = 0;
    let hi = cdf.length - 1;
    while (lo < hi) {
        const mid = Math.floor((lo + hi) / 2);
        if (cdf[mid] >= t) {
            hi = mid;
        } else {
            lo = mid + 1;
        }
    }
    return values[lo];
}

export function computeRademacherGj(j, t) {
    const table = buildRademacherGjTable(j);
    return inverseDiscreteCdf(table.values, table.cdf, t);
}

function buildRademacherConditionalLeftSupport(M, y) {
    const low = Math.max(-M, y - M);
    const high = Math.min(M, y + M);
    const parity = M & 1;
    const out = [];

    for (let ell = low; ell <= high; ell += 1) {
        if ((Math.abs(ell) & 1) === parity) {
            out.push(ell);
        }
    }
    return out;
}

export function buildRademacherConditionalGqTable(q, y) {
    if (!Number.isInteger(q) || q < 1 || q > 16) {
        throw new Error("q must be an integer in [1, 16]");
    }
    if (!Number.isInteger(y)) {
        throw new Error("y must be an integer");
    }

    const m = 2 ** q;
    const M = m / 2; // Each child block has length M = 2^(q-1).

    if (Math.abs(y) > m) {
        throw new Error("y must satisfy |y| <= 2^q");
    }
    if (((m + y) & 1) !== 0) {
        throw new Error("y must have the same parity as 2^q");
    }

    const leftValues = buildRademacherConditionalLeftSupport(M, y);
    const logMass = [];

    // Hypergeometric-type conditional law for left child given parent sum y.
    for (let i = 0; i < leftValues.length; i += 1) {
        const ell = leftValues[i];
        const kLeft = (M + ell) / 2;
        const kTotal = (m + y) / 2;
        logMass.push(
            logBinomial(M, kLeft) +
            logBinomial(M, kTotal - kLeft) -
            logBinomial(m, kTotal)
        );
    }

    const maxLog = Math.max(...logMass);
    const unnormalized = logMass.map((x) => Math.exp(x - maxLog));
    const z = unnormalized.reduce((a, b) => a + b, 0);
    const pmf = unnormalized.map((x) => x / z);

    // Return the law of \tilde U = left - right = 2*left - y.
    const values = leftValues.map((ell) => 2 * ell - y);
    const cdf = [];
    let acc = 0;
    for (let i = 0; i < pmf.length; i += 1) {
        acc += pmf[i];
        cdf.push(acc);
    }
    cdf[cdf.length - 1] = 1;

    return {
        q,
        y,
        m,
        values,
        pmf,
        cdf,
    };
}

export function computeRademacherConditionalGq(q, t, y) {
    // Discrete generalized inverse for the conditional CDF F_q(. | y).
    const table = buildRademacherConditionalGqTable(q, y);
    return inverseDiscreteCdf(table.values, table.cdf, t);
}
